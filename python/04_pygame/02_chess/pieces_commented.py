def draw_knight(surf, cell_x, cell_y, color):
    # Конь — самая сложная фигура. Рисуется из множества деталей:
    # основание, 4 ноги с копытами, тело, шея (из двух частей),
    # голова, морда, ухо, грива (3 пряди), хвост, глаз.

    temp = pygame.Surface((400, 400), pygame.SRCALPHA)
    cx, cy = 200, 200

    # ═══════════════════════════════════════════════════════════
    # ОСНОВАНИЕ
    # ═══════════════════════════════════════════════════════════
    w, h = 90, 25
    x = cx - w // 2
    y = cy + 45
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # НОГИ (4 штуки)
    # ═══════════════════════════════════════════════════════════
    leg_w, leg_h = 10, 40
    # Координаты X для 4 ног: -28, -10, +10, +28 от центра
    for lx in [cx - 28, cx - 10, cx + 10, cx + 28]:
        # Сама нога
        pygame.draw.rect(temp, OUTLINE, (lx - 2, cy + 5 - 2, leg_w + 4, leg_h + 4))
