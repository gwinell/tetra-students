import pygame
# ↑ Подключаем библиотеку pygame — она даёт инструменты для 2D-графики:
#   Surface (холсты), draw (примитивы), transform (масштабирование) и др.

# ═══════════════════════════════════════════════════════════════
# ГЛОБАЛЬНЫЕ КОНСТАНТЫ
# ═══════════════════════════════════════════════════════════════

CELL = 80
# ↑ Размер одной клетки шахматной доски в пикселях.
#   Все фигуры масштабируются именно под этот размер.
#   Если изменить CELL, весь код адаптируется автоматически.

OUTLINE = (30, 30, 30)
# ↑ Цвет обводки (контура) вокруг каждой детали фигуры.
#   Почти чёрный, но не абсолютно — так выглядит мягче.
#   Каждая деталь рисуется ДВАЖДЫ: сначала OUTLINE (чуть больше),
#   потом основной color (чуть меньше) — получается эффект толстой рамки.

# ═══════════════════════════════════════════════════════════════
# ОБЩИЙ ПРИНЦИП РИСОВАНИЯ ВСЕХ ФИГУР
# ═══════════════════════════════════════════════════════════════
#
# Каждая функция рисования работает по одной и той же схеме:
#
#   1. Создаём временный холст (temp Surface) размером 400×400 пикселей
#      с поддержкой прозрачности (флаг SRCALPHA).
#      Почему 400×400? Это "виртуальный" холст высокого разрешения.
#      На нём рисовать удобнее — координаты круглые, детали чёткие.
#
#   2. Определяем центр этого холста: cx = 200, cy = 200.
#      Все детали фигуры позиционируются ОТНОСИТЕЛЬНО центра.
#      Это позволяет легко центрировать фигуру в клетке.
#
#   3. Рисуем фигуру кусочками: основание, тело, голова и т.д.
#      Каждый кусочек — это прямоугольник (pygame.draw.rect).
#      Для каждого кусочка делаем ДВА вызова:
#        - Сначала рисуем чуть УВЕЛИЧЕННЫЙ прямоугольник цветом OUTLINE
#          (смещаем на -2 и увеличиваем размер на +4 — получается обводка)
#        - Потом рисуем "правильный" прямоугольник цветом color
#      Так создаётся эффект толстой чёрной обводки вокруг каждой детали.
#
#   4. Масштабируем temp с 400×400 до CELL×CELL.
#      pygame.transform.scale сжимает/растягивает изображение.
#      Фигура теперь идеально вписывается в клетку доски.
#
#   5. Копируем (blit) масштабированную фигуру на основной экран (surf)
#      в координаты (cell_x, cell_y) — левый верхний угол клетки.
#
#   Почему так сложно, а не нарисовать сразу на экране?
#   - Масштабирование даёт плавные края при любом размере CELL
#   - Центрирование относительно (200, 200) упрощает позиционирование
#   - Можно легко менять CELL, не пересчитывая все координаты
# ═══════════════════════════════════════════════════════════════


def draw_king(surf, cell_x, cell_y, color):
    # surf      — основной экран (куда копировать готовую фигуру)
    # cell_x    — X-координата левого верхнего угла клетки на доске
    # cell_y    — Y-координата левого верхнего угла клетки на доске
    # color     — цвет заливки фигуры (WHITE_PIECE или BLACK_PIECE)

    # ── ШАГ 1: Создаём временный прозрачный холст 400×400 ──
    temp = pygame.Surface((400, 400), pygame.SRCALPHA)
    # Флаг SRCALPHA включает альфа-канал (прозрачность).
    # Без него фон temp был бы чёрным, и он закрасил бы клетку доски.

    cx, cy = 200, 200
    # Центр временного холста. Все координаты считаем отсюда.

    # ═══════════════════════════════════════════════════════════
    # БОЛЬШОЕ ОСНОВАНИЕ (самая нижняя часть короля)
    # ═══════════════════════════════════════════════════════════
    w, h = 100, 30          # ширина и высота прямоугольника
    x = cx - w // 2         # центрируем по горизонтали: левый край = центр - половина ширины
    y = cy - h + 40         # позиционируем по вертикали: чуть ниже центра холста
    # Рисуем ОБВОДКУ: прямоугольник на 2 пикселя больше со всех сторон
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    # Рисуем ЗАЛИВКУ: "правильный" прямоугольник поверх обводки
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # СРЕДНЕЕ ОСНОВАНИЕ (ступенька поверх большого)
    # ═══════════════════════════════════════════════════════════
    w, h = 80, 20
    x = cx - w // 2
    y = cy - h + 40 - 30    # на 30 пикселей выше большого основания (его высота)
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # ТЕЛО (высокий прямоугольник в центре)
    # ═══════════════════════════════════════════════════════════
    w, h = 50, 110
    x = cx - w // 2
    y = cy - h + 40 - 30 - 20  # выше среднего основания (его высота 20)
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # ГОЛОВА (горизонтальная планка под крестом)
    # ═══════════════════════════════════════════════════════════
    w, h = 90, 25
    x = cx - w // 2
    y = cy - h + 40 - 30 - 20 - 110  # на высоту тела выше тела
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # КРЕСТ ВЕРТИКАЛЬНЫЙ (штанга креста)
    # ═══════════════════════════════════════════════════════════
    w, h = 14, 50
    x = cx - w // 2
    y = y - h               # начинаем СВЕРХУ от головы (y ещё хранит координату головы)
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # КРЕСТ ГОРИЗОНТАЛЬНЫЙ (перекладина креста)
    # ═══════════════════════════════════════════════════════════
    w, h = 44, 14
    x = cx - w // 2
    y = y + 18              # чуть ниже верха вертикальной штанги
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ── ШАГ 4: Масштабируем 400×400 → CELL×CELL ──
    scaled = pygame.transform.scale(temp, (CELL, CELL))
    # pygame.transform.scale принимает Surface и новый размер (ширина, высота).
    # Использует простое растяжение/сжатие пикселей.

    # ── ШАГ 5: Копируем на основной экран ──
    surf.blit(scaled, (cell_x, cell_y))
    # blit = "block transfer" — копирует одно изображение на другое.
    # scaled копируется на surf в точку (cell_x, cell_y).


def draw_queen(surf, cell_x, cell_y, color):
    # Ферзь рисуется по той же схеме, но детали другие.
    # У ферзя вместо креста — три пики (шипа) наверху.

    temp = pygame.Surface((400, 400), pygame.SRCALPHA)
    cx, cy = 200, 200

    # ═══════════════════════════════════════════════════════════
    # БОЛЬШОЕ ОСНОВАНИЕ
    # ═══════════════════════════════════════════════════════════
    baseb_w = 100
    baseb_h = 30
    baseb_x = cx - baseb_w // 2
    baseb_y = cy - baseb_h + 40
    pygame.draw.rect(temp, OUTLINE, (baseb_x - 2, baseb_y - 2, baseb_w + 4, baseb_h + 4))
    pygame.draw.rect(temp, color, (baseb_x, baseb_y, baseb_w, baseb_h))

    # ═══════════════════════════════════════════════════════════
    # СРЕДНЕЕ ОСНОВАНИЕ
    # ═══════════════════════════════════════════════════════════
    baseb_w1 = 80
    baseb_h1 = 20
    baseb_x1 = cx - baseb_w1 // 2
    baseb_y1 = cy - baseb_h1 + 40 - baseb_h  # на высоту большого основания выше
    pygame.draw.rect(temp, OUTLINE, (baseb_x1 - 2, baseb_y1 - 2, baseb_w1 + 4, baseb_h1 + 4))
    pygame.draw.rect(temp, color, (baseb_x1, baseb_y1, baseb_w1, baseb_h1))

    # ═══════════════════════════════════════════════════════════
    # ТЕЛО (выше, чем у короля — 120 вместо 110)
    # ═══════════════════════════════════════════════════════════
    baseb_w2 = 50
    baseb_h2 = 120
    baseb_x2 = cx - baseb_w2 // 2
    baseb_y2 = cy - baseb_h2 + 40 - baseb_h1
    pygame.draw.rect(temp, OUTLINE, (baseb_x2 - 2, baseb_y2 - 2, baseb_w2 + 4, baseb_h2 + 4))
    pygame.draw.rect(temp, color, (baseb_x2, baseb_y2, baseb_w2, baseb_h2))

    # ═══════════════════════════════════════════════════════════
    # ПЕРЕХОД К ГОЛОВЕ (широкая планка)
    # ═══════════════════════════════════════════════════════════
    baseb_w3 = 80
    baseb_h3 = 20
    baseb_x3 = cx - baseb_w3 // 2
    baseb_y3 = cy - baseb_h3 + 40 - baseb_h2
    pygame.draw.rect(temp, OUTLINE, (baseb_x3 - 2, baseb_y3 - 2, baseb_w3 + 4, baseb_h3 + 4))
    pygame.draw.rect(temp, color, (baseb_x3, baseb_y3, baseb_w3, baseb_h3))

    # ═══════════════════════════════════════════════════════════
    # ГОЛОВА (широкая верхняя планка)
    # ═══════════════════════════════════════════════════════════
    baseb_w4 = 110
    baseb_h4 = 30
    baseb_x4 = cx - baseb_w4 // 2
    baseb_y4 = cy - baseb_h4 + 40 - baseb_h2
    pygame.draw.rect(temp, OUTLINE, (baseb_x4 - 2, baseb_y4 - 2, baseb_w4 + 4, baseb_h4 + 4))
    pygame.draw.rect(temp, color, (baseb_x4, baseb_y4, baseb_w4, baseb_h4))

    # ═══════════════════════════════════════════════════════════
    # ТРИ ПИКИ (шипа наверху ферзя)
    # ═══════════════════════════════════════════════════════════
    # Ширина одной пики = ширина головы / 5
    baseb_w5 = baseb_w4 // 5   # 110 // 5 = 22 пикселя
    baseb_h5 = 40              # высота пики
    baseb_x5 = baseb_x4        # левая пика — начинается с левого края головы
    baseb_y5 = baseb_y4 - baseb_h5  # на высоту пики выше головы
    pygame.draw.rect(temp, OUTLINE, (baseb_x5 - 2, baseb_y5 - 2, baseb_w5 + 4, baseb_h5 + 4))
    pygame.draw.rect(temp, color, (baseb_x5, baseb_y5, baseb_w5, baseb_h5))

    # Средняя пика (смещена на 2 ширины пики вправо)
    baseb_w6 = baseb_w5
    baseb_h6 = baseb_h5
    baseb_x6 = baseb_x5 + baseb_w6 * 2
    baseb_y6 = baseb_y5
    pygame.draw.rect(temp, OUTLINE, (baseb_x6 - 2, baseb_y6 - 2, baseb_w6 + 4, baseb_h6 + 4))
    pygame.draw.rect(temp, color, (baseb_x6, baseb_y6, baseb_w6, baseb_h6))

    # Правая пика (ещё на 2 ширины вправо)
    baseb_w7 = baseb_w6
    baseb_h7 = baseb_h6
    baseb_x7 = baseb_x6 + baseb_w6 * 2
    baseb_y7 = baseb_y6
    pygame.draw.rect(temp, OUTLINE, (baseb_x7 - 2, baseb_y7 - 2, baseb_w7 + 4, baseb_h7 + 4))
    pygame.draw.rect(temp, color, (baseb_x7, baseb_y7, baseb_w7, baseb_h7))

    scaled = pygame.transform.scale(temp, (CELL, CELL))
    surf.blit(scaled, (cell_x, cell_y))


def draw_rook(surf, cell_x, cell_y, color):
    # Ладья — массивная фигура с зубцами (башенками) наверху.

    temp = pygame.Surface((400, 400), pygame.SRCALPHA)
    cx, cy = 200, 200

    # ═══════════════════════════════════════════════════════════
    # ОСНОВАНИЕ (широкое, низкое)
    # ═══════════════════════════════════════════════════════════
    base_x = cx - 40        # центр - половина ширины (80/2)
    base_y = cy + 20        # чуть ниже центра
    base_w = 80
    base_h = 25
    pygame.draw.rect(temp, OUTLINE, (base_x - 2, base_y - 2, base_w + 4, base_h + 4))
    pygame.draw.rect(temp, color, (base_x, base_y, base_w, base_h))

    # ═══════════════════════════════════════════════════════════
    # СТВОЛ (узкий прямоугольник посередине)
    # ═══════════════════════════════════════════════════════════
    body_x = cx - 20        # центр - 10 (ширина 40)
    body_y = cy - 20
    body_w = 40
    body_h = 45
    pygame.draw.rect(temp, OUTLINE, (body_x - 2, body_y - 2, body_w + 4, body_h + 4))
    pygame.draw.rect(temp, color, (body_x, body_y, body_w, body_h))

    # ═══════════════════════════════════════════════════════════
    # ГОЛОВА С ЗУБЦАМИ (горизонтальная балка)
    # ═══════════════════════════════════════════════════════════
    head_x = body_x - 10    # шире ствола на 10 с каждой стороны
    head_y = body_y - 20
    head_w = 60
    head_h = 20
    pygame.draw.rect(temp, OUTLINE, (head_x - 2, head_y - 2, head_w + 4, head_h + 4))
    pygame.draw.rect(temp, color, (head_x, head_y, head_w, head_h))

    # ═══════════════════════════════════════════════════════════
    # ЗУБЦЫ (5 маленьких прямоугольников сверху головы)
    # ═══════════════════════════════════════════════════════════
    tooth_w = head_w // 5   # ширина каждого зубца = ширина головы / 5 = 12
    tooth_h = 12
    for i in range(5):      # цикл от 0 до 4 — 5 зубцов
        tx = head_x + i * tooth_w   # X каждого зубца: 0, 12, 24, 36, 48
        ty = head_y - tooth_h       # Y — на высоту зубца выше головы
        pygame.draw.rect(temp, OUTLINE, (tx - 2, ty - 2, tooth_w + 4, tooth_h + 4))
        pygame.draw.rect(temp, color, (tx, ty, tooth_w, tooth_h))

    # ═══════════════════════════════════════════════════════════
    # ЦЕНТРАЛЬНАЯ ПИКА (выше всех зубцов, по центру)
    # ═══════════════════════════════════════════════════════════
    # Рисуем обводку: ширина 24, высота 29, центрирована по cx
    pygame.draw.rect(temp, OUTLINE, (cx - 12, body_y - 47, 24, 29))
    # Рисуем заливку: чуть меньше (на 2 пикселя с каждой стороны)
    pygame.draw.rect(temp, color, (cx - 10, body_y - 45, 20, 25))

    scaled = pygame.transform.scale(temp, (CELL, CELL))
    surf.blit(scaled, (cell_x, cell_y))


