def draw_pawn(surf, cell_x, cell_y, color):
    # Пешка — самая простая фигура: круглая голова + тело + два основания.
    # Единственная фигура, где используется ellipse (овал) вместо rect.

    temp = pygame.Surface((400, 400), pygame.SRCALPHA)
    cx, cy = 200, 200

    # ═══════════════════════════════════════════════════════════
    # ОСНОВАНИЕ (самое широкое)
    # ═══════════════════════════════════════════════════════════
    w, h = 80, 22
    x = cx - w // 2
    y = cy + 45
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # СРЕДНЕЕ ОСНОВАНИЕ
    # ═══════════════════════════════════════════════════════════
    w, h = 55, 15
    x = cx - w // 2
    y = cy + 30
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # ТЕЛО (узкий прямоугольник)
    # ═══════════════════════════════════════════════════════════
    w, h = 35, 60
    x = cx - w // 2
    y = cy - 30
    pygame.draw.rect(temp, OUTLINE, (x - 2, y - 2, w + 4, h + 4))
    pygame.draw.rect(temp, color, (x, y, w, h))

    # ═══════════════════════════════════════════════════════════
    # ГОЛОВА (овал через pygame.draw.ellipse)
    # ═══════════════════════════════════════════════════════════
    # ellipse рисует овал внутри заданного прямоугольника.
