import pygame
from pieces import (
    draw_king, draw_queen, draw_rook, draw_bishop,
    draw_knight, draw_pawn, CELL
)
# ↑ Импортируем из модуля pieces функции для отрисовки каждой шахматной фигуры
#   и константу CELL — размер одной клетки доски в пикселях.
#   Модуль pieces отвечает за графику фигур (как они выглядят), а этот файл — за логику игры.

pygame.init()
# ↑ Инициализируем библиотеку pygame. Это обязательный вызов перед использованием
#   любых функций pygame (окна, графика, события и т.д.).
#   Он подготавливает внутренние механизмы библиотеки к работе.

# ═══════════════════════════════════════════════════════════════
# ЦВЕТА
# ═══════════════════════════════════════════════════════════════
# В pygame цвет задаётся кортежем из трёх чисел (R, G, B), где каждое число
# от 0 до 255. Это стандартная RGB-модель.

LIGHT_SQUARE = (240, 217, 181)
# ↑ Светло-бежевый цвет для "белых" клеток доски.

DARK_SQUARE = (181, 136, 99)
# ↑ Тёмно-коричневый цвет для "чёрных" клеток доски.

WHITE_PIECE = (230, 230, 230)
# ↑ Почти белый цвет для белых фигур. Не чисто белый (255,255,255),
#   чтобы фигуры не сливались со светлыми клетками.

BLACK_PIECE = (60, 60, 60)
# ↑ Тёмно-серый цвет для чёрных фигур. Не чисто чёрный,
#   чтобы на тёмных клетках фигуры были видны.

# ═══════════════════════════════════════════════════════════════
# ДОСКА — представление состояния игры
# ═══════════════════════════════════════════════════════════════
# Доска — это список из 8 списков (8 рядов), каждый из которых содержит 8 элементов.
# Каждый элемент — это либо буква фигуры, либо None (пустая клетка).
#
# Обозначения фигур (стандартная шахматная нотация в программировании):
#   k = король (king)       q = ферзь (queen)
#   r = ладья (rook)        b = слон (bishop)
#   n = конь (knight)       p = пешка (pawn)
#
# Заглавные буквы (K, Q, R, B, N, P) = белые фигуры
# Строчные буквы (k, q, r, b, n, p) = чёрные фигуры
#
# Важно: в массиве board[0] — это ВЕРХНИЙ ряд экрана (чёрные фигуры),
#        board[7] — НИЖНИЙ ряд экрана (белые фигуры).
#        То есть индексы строки совпадают с координатой Y на экране.

board = [
    # Ряд 0 — чёрные тяжёлые фигуры (верх доски)
    ['r', 'n', 'b', 'q', 'k', 'b', 'n', 'r'],
    # Ряд 1 — чёрные пешки
    ['p'] * 8,
    # Ряды 2-5 — пустые клетки (середина доски)
    [None] * 8,
    [None] * 8,
    [None] * 8,
    [None] * 8,
    # Ряд 6 — белые пешки
    ['P'] * 8,
    # Ряд 7 — белые тяжёлые фигуры (низ доски)
    ['R', 'N', 'B', 'Q', 'K', 'B', 'N', 'R'],
]

# ═══════════════════════════════════════════════════════════════
# СОПОСТАВЛЕНИЕ ФИГУР С ФУНКЦИЯМИ ОТРИСОВКИ
# ═══════════════════════════════════════════════════════════════
# Словарь DRAW_MAP связывает буквенное обозначение фигуры (в нижнем регистре)
# с соответствующей функцией из модуля pieces.
# Когда нужно нарисовать фигуру, мы берём её букву, приводим к нижнему регистру
# (чтобы не различать белые и чёрные), и вызываем соответствующую функцию.

DRAW_MAP = {
    'k': draw_king,    # король
    'q': draw_queen,   # ферзь
    'r': draw_rook,    # ладья
    'b': draw_bishop,  # слон
    'n': draw_knight,  # конь
    'p': draw_pawn,    # пешка
}

# ═══════════════════════════════════════════════════════════════
# НАСТРОЙКА ОКНА PYGAME
# ═══════════════════════════════════════════════════════════════

screen = pygame.display.set_mode((CELL * 8, CELL * 8))
# ↑ Создаём игровое окно размером 8×8 клеток.
#   CELL * 8 = ширина и высота окна в пикселях.
#   Результат сохраняем в переменную screen — это "холст",
#   на который будем рисовать всё остальное.

pygame.display.set_caption("Шахматы")
# ↑ Устанавливаем заголовок окна (то, что видно в верхней панели окна).

clock = pygame.time.Clock()
# ↑ Создаём объект Clock для контроля частоты кадров.
#   Он поможет ограничить игру до 60 кадров в секунду,
#   чтобы программа не "съедала" все ресурсы процессора.

# ═══════════════════════════════════════════════════════════════
# СОСТОЯНИЕ ИГРЫ
# ═══════════════════════════════════════════════════════════════

selected = None
# ↑ Переменная для хранения координат выбранной фигуры.
#   None означает, что сейчас ничего не выбрано.
#   Когда игрок кликает на фигуру, сюда записывается кортеж (row, col).
#   row — номер строки (0 сверху, 7 снизу), col — номер столбца (0 слева, 7 справа).

# ═══════════════════════════════════════════════════════════════
# ФУНКЦИЯ ОТРИСОВКИ ДОСКИ
# ═══════════════════════════════════════════════════════════════

def draw_board():
    # Проходим по всем 8 рядам и 8 столбцам доски
    for r in range(8):      # r — номер строки (0..7)
        for c in range(8):  # c — номер столбца (0..7)

            # Определяем цвет клетки по шахматному паттерну:
            # Если сумма r + c чётная — светлая клетка, иначе — тёмная.
            # Это классический способ создания шахматной раскраски.
            color = LIGHT_SQUARE if (r + c) % 2 == 0 else DARK_SQUARE

            # Создаём прямоугольник (клетку) с координатами:
            # x = c * CELL (отступ слева), y = r * CELL (отступ сверху)
            # ширина = CELL, высота = CELL
            rect = pygame.Rect(c * CELL, r * CELL, CELL, CELL)

            # Рисуем заполненный прямоугольник указанным цветом
            pygame.draw.rect(screen, color, rect)

            # ─────────────────────────────────────────
            # Подсветка выбранной клетки
            # ─────────────────────────────────────────
            # Если текущая клетка совпадает с выбранной — рисуем вокруг неё
            # жёлтую рамку толщиной 3 пикселя, чтобы игрок видел,
            # какая фигура сейчас "в руках".
            if selected == (r, c):
                pygame.draw.rect(screen, (255, 255, 0), rect, 3)
                # Последний аргумент 3 = толщина линии рамки (не заливка!)

# ═══════════════════════════════════════════════════════════════
# ФУНКЦИЯ ОТРИСОВКИ ФИГУР
# ═══════════════════════════════════════════════════════════════

def draw_pieces():
    # Проходим по всей доске
    for r in range(8):
        for c in range(8):
            p = board[r][c]
            # p — содержимое клетки: буква фигуры или None

            if p is None:
                continue  # Пустая клетка — пропускаем, нечего рисовать

            # Получаем функцию отрисовки по букве фигуры (в нижнем регистре).
            # Например, если p = 'Q', то p.lower() = 'q', и мы берём draw_queen.
            func = DRAW_MAP[p.lower()]

            # Определяем цвет фигуры:
            # p.isupper() возвращает True для заглавных букв (белые фигуры).
            # Заглавные = белые (WHITE_PIECE), строчные = чёрные (BLACK_PIECE).
            color = WHITE_PIECE if p.isupper() else BLACK_PIECE

            # Вызываем функцию отрисовки с параметрами:
            #   screen — куда рисовать
            #   c * CELL — координата X левого верхнего угла клетки
            #   r * CELL — координата Y левого верхнего угла клетки
            #   color — цвет фигуры (белый или чёрный)
            func(screen, c * CELL, r * CELL, color)

# ═══════════════════════════════════════════════════════════════
# ГЛАВНЫЙ ИГРОВОЙ ЦИКЛ
# ═══════════════════════════════════════════════════════════════
# Это сердце любой pygame-программы. Цикл выполняется снова и снова,
# пока переменная running == True. Каждая итерация = один кадр игры.

running = True
while running:

    # ─────────────────────────────────────────
    # 1. ОБРАБОТКА СОБЫТИЙ
    # ─────────────────────────────────────────
    # Pygame накапливает события (клики мыши, нажатия клавиш, закрытие окна)
    # в очереди. Мы должны их все обработать.

    for event in pygame.event.get():
        # event — объект, описывающий одно событие

        if event.type == pygame.QUIT:
            # Пользователь нажал крестик на окне — выходим из игры
            running = False

        elif event.type == pygame.MOUSEBUTTONDOWN:
            # Пользователь нажал кнопку мыши

            # event.pos — кортеж (x, y) с координатами клика в пикселях
            # Делим на CELL, чтобы перевести пиксели в номера клеток
            col = event.pos[0] // CELL   # X-координата → номер столбца
            row = event.pos[1] // CELL   # Y-координата → номер строки

            if selected is None:
                # ═══════════════════════════════════════════════
                # ФАЗА 1: ВЫБОР ФИГУРЫ
                # ═══════════════════════════════════════════════
                # Если ещё ничего не выбрано — пробуем выбрать фигуру
                if board[row][col] is not None:
                    # Клетка не пустая — запоминаем её как выбранную
                    selected = (row, col)
                    # Теперь draw_board() подсветит эту клетку жёлтой рамкой
            else:
                # ═══════════════════════════════════════════════
                # ФАЗА 2: ПЕРЕМЕЩЕНИЕ ФИГУРЫ
                # ═══════════════════════════════════════════════
                # Фигура уже выбрана — теперь клик определяет куда её поставить

                if (row, col) != selected:
                    # Если кликнули НЕ на ту же клетку — перемещаем фигуру
                    # (пока без проверки правил: можно ходить куда угодно!)

                    # Копируем фигуру на новую позицию
                    board[row][col] = board[selected[0]][selected[1]]
                    # Очищаем старую позицию (ставим None)
                    board[selected[0]][selected[1]] = None

                # В любом случае (даже если кликнули на ту же клетку)
                # сбрасываем выбор — ход завершён
                selected = None

    # ─────────────────────────────────────────
    # 2. ОТРИСОВКА КАДРА
    # ─────────────────────────────────────────
    # Порядок отрисовки важен! То, что рисуем позже, накладывается сверху.

    screen.fill((0, 0, 0))
    # Заливаем весь экран чёрным. Это нужно, чтобы стереть кадр предыдущей
    # итерации. Без этого старые изображения "наслаивались" бы друг на друга.

    draw_board()
    # Рисуем клетки доски (светлые/тёмные + подсветка выбранной)

    draw_pieces()
    # Рисуем фигуры поверх доски. Фигуры должны быть ПОСЛЕ доски,
    # иначе доска закрасит их!

    pygame.display.flip()
    # "Переворачиваем" экран: показываем всё, что нарисовали.
    # До этого момента рисование происходило в "скрытом" буфере.
    # flip() делает его видимым для пользователя.

    clock.tick(60)
    # Ограничиваем скорость цикла до 60 итераций в секунду (60 FPS).
    # Без этого цикл мог бы работать на тысячах FPS и нагружать процессор.

pygame.quit()
# Завершаем работу pygame (освобождаем ресурсы, закрываем окно)